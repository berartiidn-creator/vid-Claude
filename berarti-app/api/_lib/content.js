const FAITH_NOTE = 'Kamu menyebut ingin hidupmu bernilai di hadapan manusia dan Tuhan. Kalau kamu nyaman, jadikan niat itu pengingat setiap kali memulai langkah di Peta 90 Hari.';

export function buildReport({ scores, tier, reflection, model }) {
  const { strongest, weakest, secondWeakest, ARCHETYPES } = model;
  const top = strongest(scores), low = weakest(scores), low2 = secondWeakest(scores);
  const report = {
    archetype: ARCHETYPES[top].name, strongest: top, weakest: low,
    pola: POLA[top], titikButa: TITIK_BUTA[top], caraPikir: CARA_PIKIR[top],
    pedeBelumDipakai: PEDE_BELUM_DIPAKAI[low2], tujuhHari: TUJUH_HARI[low],
    faith: reflection === 'ya' ? FAITH_NOTE : null,
  };
  if (tier === 'arah90') report.peta90 = PETA90[low];
  return report;
}
